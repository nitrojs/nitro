import type { ConsolaInstance } from "./_consola.ts";
import type { Hookable } from "./_hookable.ts";
import type { PresetName, PresetOptions } from "../presets/index.ts";
import type { NitroConfig, NitroOptions } from "./config.ts";
import type { NitroEventHandler } from "./handler.ts";
import type { NitroHooks } from "./hooks.ts";
import type { PrerenderRoute } from "./prerender.ts";
import type { Router } from "../routing.ts";
import type { NormalizedRouteRules } from "./route-rules.ts";
import type { WorkerAddress } from "./runner.ts";

type MaybeArray<T> = T | T[];

/** Nitro package metadata including version information. */
export interface NitroMeta {
  version: string;
  majorVersion: number;
}

/**
 * The core Nitro instance available throughout the build lifecycle.
 *
 * Provides access to resolved options, hooks, the virtual file system,
 * scanned handlers, and utility methods.
 */
export interface Nitro {
  meta: NitroMeta;
  options: NitroOptions;
  scannedHandlers: NitroEventHandler[];
  vfs: Map<string, { render: () => string | Promise<string> }>;
  hooks: Hookable<NitroHooks>;
  logger: ConsolaInstance;
  fetch: (input: Request) => Response | Promise<Response>;
  close: () => Promise<void>;
  updateConfig: (config: NitroDynamicConfig) => void | Promise<void>;
  routing: Readonly<{
    sync: () => void;
    routeRules: Router<NormalizedRouteRules & { _route: string }>;
    routes: Router<MaybeArray<NitroEventHandler & { _importHash: string }>>;
    globalMiddleware: (NitroEventHandler & { _importHash: string })[];
    routedMiddleware: Router<NitroEventHandler & { _importHash: string }>;
  }>;

  /** Routes generated by the last `prerender()` run. */
  _prerenderedRoutes?: PrerenderRoute[];

  /**
   * Page template provided by a builder integration (e.g. `nitro/vite`), compiled into the
   * renderer template at build time (in development too).
   *
   * @internal
   */
  _pageTemplate?: {
    /**
     * Returns the page HTML (e.g. the client HTML transformed by the builder).
     *
     * Defaults to the contents of `renderer.template`.
     */
    html?: () => string | undefined | Promise<string | undefined>;

    /** Imports added to the template context (e.g. `fetchViteEnv`). */
    context?: { from: string; name: string }[];
  };

  /**
   * Set by the builder integration that builds the `services` (e.g. `nitro/vite`): how the
   * server loads the output of each service.
   *
   * @internal
   */
  _serviceLoader?: (name: string) => NitroServiceLoader;
}

/**
 * How the server loads the output of a service.
 *
 * - `import`: module (path or id) imported on the first fetch, bundled by Nitro in production.
 *   With `bundle: false`, the module (e.g. a file URL of the service output in development) is
 *   imported at runtime, not bundled. A failed import is retried by the next fetch.
 * - `expression`: JavaScript expression evaluated on each fetch, returning the `{ fetch }`
 *   service (e.g. registered by a dev worker on `globalThis`).
 */
export type NitroServiceLoader = { import: string; bundle?: false } | { expression: string };

/**
 * Subset of {@link NitroConfig} that can be updated at runtime via
 * `nitro.updateConfig()`.
 */
export type NitroDynamicConfig = Pick<NitroConfig, "runtimeConfig" | "routeRules">;

/**
 * Metadata about the framework using Nitro.
 *
 * @see https://nitro.build/config/advanced#framework
 */
export interface NitroFrameworkInfo {
  name?: "nitro" | (string & {});
  version?: string;
  /**
   * Command shown in build output as the suggested preview command.
   *
   * Display-only: Nitro never executes this. Use this when the framework
   * wraps `nitro preview` with its own CLI (e.g. `npx nuxt preview`).
   * Defaults to `npx nitro preview`.
   */
  previewCommand?: string;
  /**
   * Command shown in build output as the suggested deploy command.
   *
   * Display-only: Nitro never executes this. Use this when the framework
   * wraps `nitro deploy` with its own CLI (e.g. `npx nuxt deploy`).
   * Defaults to `npx nitro deploy --prebuilt`.
   */
  deployCommand?: string;
}

/**
 * Build info written to `<output.dir>/nitro.json` (production, default
 * `.output/nitro.json`) or `<rootDir>/node_modules/.nitro/nitro.dev.json`
 * (development).
 *
 * Contains preset, framework, version, and command information.
 */
export interface NitroBuildInfo {
  date: string;
  preset: PresetName;
  envName?: string;
  framework: NitroFrameworkInfo;
  versions: {
    nitro: string;
    [key: string]: string;
  };
  commands?: {
    preview?: string;
    deploy?: string;
  };
  serverEntry?: string;
  publicDir?: string;
  dev?: {
    pid: number;
    workerAddress?: WorkerAddress;
    /** Public URL of the dev server (its first listener). */
    url?: string;
  };
  config?: Partial<PresetOptions>;
}
